/**
 * build_city_images_manifest , writes data/cities/images_manifest.json from the
 * files that EXIST in public/cities/, one per city slug (<slug>.jpeg). The
 * manifest is what the pager card and the city hero read (founder ruling 2 of
 * 2026-09-04: the card's image is the city hero's image), so a card can never
 * point at a photo that is not there. Run after adding photos:
 *   npx tsx scripts/build_city_images_manifest.ts
 * The asset contract: JPEG, 4:3, at least 640x480, under 160KB, a real
 * photograph the atlas has the right to show; the credit belongs in
 * data/cities/images_credits.json beside it (kept by hand).
 *
 * THE SMALL COPIES AND THE CROPS (plan 2026-10-10, the home reformed to ship, Task 6; the critique's P1.11, the ship audit's 3.3):
 * the home's rows are 44 to 64px tall and drew the 960 by 720 photographs, about 1 MB for seven rows. With `--thumbs` this writes a
 * 480 by 360 copy of each photograph to public/cities/thumbs/<slug>.jpeg (centre cut, JPEG quality 65, progressive: about 25KB
 * each) with sharp, the image library already in node_modules (it comes with next; nothing is installed or downloaded); without
 * it the folder is read as it stands. A city's entry names its small copy (`thumb`) where the file exists, and its crop
 * (`position`, the CSS object-position that keeps its landmark in a short row) from the credits, where it is chosen by hand.
 *   npx tsx scripts/build_city_images_manifest.ts --thumbs
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";

const dir = "public/cities";
const thumbs = "public/cities/thumbs";
/** The small copy: 4:3 at 480 by 360, twice the widest phone cell, at quality 65. */
const THUMB = { width: 480, height: 360, quality: 65 };

async function main(): Promise<void> {
  const credits = existsSync("data/cities/images_credits.json")
    ? (JSON.parse(readFileSync("data/cities/images_credits.json", "utf8")) as { photos?: Record<string, { alt?: string; position?: string }> }).photos ?? {}
    : {};
  /* A folder with no photograph in it is an empty manifest, not a crash: since
     2026-09-11 no covered city holds one (the London file was the street map he
     ruled out by name, and it left this folder), and a fresh clone may not carry
     the folder at all. */
  const photos = (existsSync(dir) ? readdirSync(dir) : []).filter((f) => /^([a-z0-9-]+)\.(jpe?g)$/i.test(f));
  if (process.argv.includes("--thumbs")) {
    const { default: sharp } = await import("sharp");
    mkdirSync(thumbs, { recursive: true });
    for (const f of photos) {
      await sharp(path.join(dir, f)).resize(THUMB.width, THUMB.height, { fit: "cover", position: "centre" }).jpeg({ quality: THUMB.quality, mozjpeg: true, progressive: true }).toFile(path.join(thumbs, f));
    }
    console.log(`city thumbnails: ${photos.length} written to ${thumbs} at ${THUMB.width} by ${THUMB.height}`);
  }
  const out: Record<string, { file: string; bytes: number; thumb?: string; position?: string }> = {};
  for (const f of photos) {
    const slug = (/^([a-z0-9-]+)\.(jpe?g)$/i.exec(f) as RegExpExecArray)[1];
    const position = credits[slug.toLowerCase()]?.position;
    out[slug] = {
      file: `/cities/${f}`,
      bytes: statSync(path.join(dir, f)).size,
      ...(existsSync(path.join(thumbs, f)) ? { thumb: `/cities/thumbs/${f}` } : {}),
      ...(position ? { position } : {}),
    };
  }
  writeFileSync("data/cities/images_manifest.json", JSON.stringify({ anchor: "Generated by scripts/build_city_images_manifest.ts from public/cities. Do not edit by hand.", cities: out }, null, 2) + "\n");
  console.log("city images:", Object.keys(out).length, Object.keys(out).join(" "));

  /* THE COUNTRY PHOTOGRAPHS (2026-09-25), the same contract one level up: public/countries/<iso2>.jpeg, read into
     data/cities/country_images_manifest.json, which the country hero reads (hero_board.ts heroImageFor). The alt text comes from
     the hand-kept record of where each photograph came from (data/cities/images_credits.json), so a photograph with no record
     draws with an empty alt rather than a guessed one. NOT data/countries/: that folder is the cell lattice's, one file a country
     named by its slug (scripts/verify_cell_lattice.mjs, X2), and a manifest there read as the first country file and failed every
     cell for its missing country (the chain of 2026-09-25, batch 24). */
  const cdir = "public/countries";
  const countries: Record<string, { file: string; bytes: number; alt: string }> = {};
  for (const f of existsSync(cdir) ? readdirSync(cdir) : []) {
    const m = /^([a-z]{2})\.(jpe?g)$/i.exec(f);
    if (!m) continue;
    countries[m[1].toLowerCase()] = { file: `/countries/${f}`, bytes: statSync(path.join(cdir, f)).size, alt: credits[m[1].toLowerCase()]?.alt ?? "" };
  }
  writeFileSync("data/cities/country_images_manifest.json", JSON.stringify({ anchor: "Generated by scripts/build_city_images_manifest.ts from public/countries. Do not edit by hand.", countries }, null, 2) + "\n");
  console.log("country images:", Object.keys(countries).length, Object.keys(countries).join(" "));
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
