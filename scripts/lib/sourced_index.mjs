/**
 * scripts/lib/sourced_index.mjs , THE FILES OF data/sourced/ AND THE MODULE THAT IMPORTS THEM (plan 2026-10-17 replicable pages,
 * Task 4). The loader (src/lib/sourced/load.ts) reads data/sourced/ only through src/lib/sourced/files.ts, a list of static JSON
 * imports, so a page never touches the file system at runtime. sourcedJsonFiles walks data/sourced/<domain>/ for *.json (by path from
 * the root, no name skipped); indexSource writes the module those files make. scripts/gen_sourced_index.ts writes it, the
 * sourced-data gate compares it.
 */
import { existsSync, readdirSync, statSync } from "node:fs";
import { join, relative, sep } from "node:path";

export const SOURCED_DIR = "data/sourced";
export const INDEX_FILE = "src/lib/sourced/files.ts";

/** Every *.json under data/sourced/, repo-relative with forward slashes, sorted. */
export function sourcedJsonFiles(root = SOURCED_DIR) {
  const out = [];
  const walk = (dir) => {
    for (const name of readdirSync(dir)) {
      const p = join(dir, name);
      if (statSync(p).isDirectory()) walk(p);
      else if (name.endsWith(".json")) out.push(relative(".", p).split(sep).join("/"));
    }
  };
  if (existsSync(root)) walk(root);
  return out.sort();
}

/** The text of src/lib/sourced/files.ts for these files. */
export function indexSource(files) {
  const lines = [
    "/* GENERATED by scripts/gen_sourced_index.ts from data/sourced/ (node node_modules/tsx/dist/cli.mjs scripts/gen_sourced_index.ts).",
    " * Do not edit: the sourced-data gate reds when this list is not every file under data/sourced/. */",
    'import type { SourcedFile } from "./schema";',
  ];
  files.forEach((f, i) => lines.push(`import f${i} from "../../../${f}";`));
  lines.push("", `export const SOURCED_FILES: readonly SourcedFile[] = [${files.map((_, i) => `f${i}`).join(", ")}] as unknown as readonly SourcedFile[];`, "");
  return lines.join("\n");
}
