/**
 * The industry spine page body. `data` defaults to the bundled illustrative seed so
 * the dev route (page.tsx) renders it unchanged; the live route passes the real-data
 * seed from buildSpineIndustrySeed. Every card builds off the taxonomy id the seed
 * carries (and the slate it resolved), so an omitted field renders nothing.
 */
export function SpineIndustryBody({ data = spineIndustrySeed }: { data?: any } = {}) {
  const d = data ?? spineIndustrySeed;

  /* WHO IS HOME, ASKED ONCE (the trade view's idiom): the three opening
     builders over the taxonomy id the adapter carries (`meta.id`, the id the
     shard is filed under), so a band is drawn when its cards exist and a
     heading never sits over nothing. The take builds for every trade in the
     taxonomy (the one net builder resolves 243 of 243); the survival triple
     and the sector set build for every trade holding a shard, so the band
     `01 | 02` holds two children or does not draw. */
  const industryId: string | undefined = typeof d.meta?.id === "string" ? d.meta.id : typeof d.meta?.industry === "string" ? d.meta.industry : undefined;
  const hero = industryHeroFacts(industryId);
  const lasts = buildLasts(industryId, "world");
  const benchmark = buildBenchmark(industryId);
  /* A SECTOR WITH NOTHING TO RANK DRAWS NO BENCHMARK (the goal's A10,
     2026-09-24): since the set is the sector's live trades, four sectors hold
     under two figures of their own (game development one of one; bricklaying,
     tiling and plastering none of three), and the card would stand as a
     "Not gathered yet" line. Omitted instead, the canonical silent omission
     for data a card cannot draw; the survival card stands alone in its band. */
  const benchmarkDrawn = benchmark != null && benchmark.state !== "withheld" ? benchmark : null;
  /* TURN ONE'S THREE, off the same id (plan step 34's second dispatch): the
     split on the trade's builder at the world altitude (the one net builder
     with the engine absent, the hero's own figure), the open card over the
     trade's permits and open builders, the bento over the shard's roles,
     first-year rows and cost stack. Each builds for every trade holding a
     shard, so the band `03 | 04` holds two children or does not draw, and
     the bento draws its four cells or not at all. */
  const split = buildIndustrySplit(industryId);
  const open = buildIndustryOpen(industryId);
  const pays = buildPays(industryId);
  /* TURN TWO'S THREE (plan step 34's third dispatch): the places off the
     slate the adapter resolved (`across`: the columns, or an empty list for
     a trade the slate does not measure anywhere; absent on the bundled dev
     seed, where no lookup was made and the block builds nothing), the
     formats off the shard on the one net builder, the mix off the shard at
     the world altitude. The places block ships as the table or the seat and
     is never dropped where a slate was resolved; the formats and the mix
     build for every trade holding a shard, so the band `07 | 08` holds two
     children or does not draw. */
  const places = buildIndustryPlaces(industryId, d.across);
  const formats = buildFormats(industryId);
  const mix = buildMix(industryId, "world");
  /* TURN THREE'S TWO AND THE EXIT (plan step 34's fourth dispatch): the
     notes off the trade's authored character and failure modes (every
     taxonomy id builds a card: the notes, or the one row), the field off
     the trade's market builder at the world altitude (every shard), so the
     band `09 | 10` holds two children or does not draw; the doors off the
     places and benchmark results built above, the pill on every trade. */
  const know = buildKnow(industryId);
  const field = buildMarket(industryId, "world");
  const doors = buildIndustryCloseDoors(industryId, places, benchmark);

  /* The turns, by whether a card stands under each. */
  const turnOne = (!!split && !!open) || !!pays;
  /* `06 places` draws only as the table (four cities holding their own figures): the drawn blocked seat printed "Not gathered yet: own figures in 2 of 15 cities" on the restaurants page he is shown, the line he refused on 2026-09-19 (the senior review of 2026-09-20; the trade's peers and the city's locals seats left the same way). The component keeps its seated branch for the sheet's story; the page draws the seat on no trade. */
  const placesDrawn = !!places && places.state === "table";
  const turnTwo = placesDrawn || (!!formats && !!mix);
  const turnThree = !!know && !!field;

  /* THE BAND PAGE (2026-10-04, his "push forward man" after the United Kingdom's band page went live; MODEL.md PART 10): each level
     a zone, the tone by its place, the sections open on it, each chapter's number and title on the first zone it owns. The answer;
     how long a trade lasts beside the sector's keep (1-2, or the survival alone at two thirds); 01 where the money goes beside what
     it takes to open (2-1), then what the trade pays (its cluster, the whole column); 02 the places table (the whole column), then
     the formats beside the channels (2-1); 03 what owners say beside the field (2-1); the close. The splits and the tablet's
     stacking are the bento's, measured there (this file before 2026-10-04 carries the numbers). */
  const oneFirst = !!split && !!open;
  const twoFirst = placesDrawn;
  return (
    <>
      {/* NO MAIN AND NO GUTTER OF ITS OWN (the goal's A13, 2026-09-24): every route that draws this body wraps it in SiteChrome. */}
      {/* THE TRAIL BACK UP (Crumbs.tsx, 2026-09-22): the real hierarchy, every step resolved through page_targets.ts, the last step the page itself. */}
      <Crumbs items={buildIndustryCrumbs(industryId)} />
      <div className="-mx-2 md:mx-0" data-spine-body data-composition="zones">
        <Zone split="wide" label="The answer">
          <Masthead facts={hero} />
        </Zone>
        {lasts ? (
          <Zone split={benchmarkDrawn ? "1-2" : "2-1"} stack="lg" label="How long it lasts">
            <LastsCard lasts={lasts} list={!!benchmarkDrawn} />
            {benchmarkDrawn ? <BenchmarkCard benchmark={benchmarkDrawn} /> : null}
          </Zone>
        ) : null}
        {turnOne && oneFirst ? (
          <Zone split="2-1" stack="lg" label={COPY.industryChapters.costs} chapter={{ index: "01", heading: COPY.industryChapters.costs }}>
            <SplitCard split={split} />
            <OpenCard open={open} />
          </Zone>
        ) : null}
        {turnOne && pays ? (
          <Zone split="wide" label="What it pays back" chapter={oneFirst ? undefined : { index: "01", heading: COPY.industryChapters.costs }}>
            <PaysBand pays={pays} />
          </Zone>
        ) : null}
        {turnTwo && twoFirst ? (
          <Zone split="wide" label={COPY.industryChapters.where} chapter={{ index: "02", heading: COPY.industryChapters.where }}>
            <PlacesTable places={places} />
          </Zone>
        ) : null}
        {turnTwo && formats && mix ? (
          <Zone split="2-1" label="Formats and channels" chapter={twoFirst ? undefined : { index: "02", heading: COPY.industryChapters.where }}>
            <FormatsCard formats={formats} oneColumn />
            <ChannelsCard id="channels" mix={mix} />
          </Zone>
        ) : null}
        {turnThree ? (
          <Zone split="2-1" stack="lg" label={COPY.industryChapters.trade} chapter={{ index: "03", heading: COPY.industryChapters.trade }}>
            <KnowCard know={know} />
            <FieldCard market={field} />
          </Zone>
        ) : null}
        {doors.length > 0 ? (
          <Zone split="wide" label="Where to next">
            {/* The exit on the hero band the bento's close stood on: the page's third full width, the full-width gates' sanction. */}
            <div data-hero="1">
              <CloseCard doors={doors} />
            </div>
          </Zone>
        ) : null}
      </div>
    </>
  );
}
